export interface SoftDelete {
  field: string;
  /** "now" stamps a timestamp; any other string is written as a status. */
  value: "now" | string;
  /** Value written on restore. `null` clears a timestamp. */
  restore: string | null;
  /** A revoked session must stay revoked, so it opts out of restore. */
  restorable?: boolean;
}

export interface ResourceDef {
  key: string;
  /** Prisma delegate name. */
  model: string;
  label: string;
  plural: string;
  group: ResourceGroup;
  icon: IconName;
  /** `entityType` on audit rows written about this table. */
  entityType: string;
  /** Field shown as the record's name. */
  title: string;
  subtitle?: string;
  /** Free-text search, substring match. */
  search: string[];
  /** Human references matched exactly (order numbers, ticket references). */
  exact?: string[];
  status?: string;
  softDelete?: SoftDelete;
  hardDelete?: boolean;
  read: AdminPermission;
  /** `null` makes the table read-only in the console. */
  write: AdminPermission | null;
  columns: string[];
  fields: FieldDef[];
  sort: { field: string; dir: "asc" | "desc" };
  /** Shown on read-only and partly-editable tables, so staff know why. */
  note?: string;
  publicPath?: (row: Record<string, unknown>) => string | null;
  children?: { resource: string; field: string; label: string }[];
}

// ---------------------------------------------------------------------------
// Field builders — terse on purpose, there are a few hundred of these
// ---------------------------------------------------------------------------

type Opts = Partial<Omit<FieldDef, "key" | "label" | "type">>;
const edit = { editable: true } as const;

const id = (): FieldDef => ({ key: "id", label: "ID", type: "id" });
const text = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "text", max: 200, ...o });
const area = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "textarea", max: 5000, ...o });
const email = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "email", ...o });
const url = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "url", ...o });
const int = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "int", ...o });
const float = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "float", ...o });
const money = (key: string, label: string, o: Opts = {}): FieldDef => ({
  key,
  label,
  type: "money",
  currencyField: "currency",
  min: 0,
  ...o,
});
const bps = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "bps", min: 0, max: 5000, ...o });
const bool = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "boolean", ...o });
const enm = (key: string, label: string, options: readonly string[], o: Opts = {}): FieldDef => ({
  key,
  label,
  type: "enum",
  options,
  filter: true,
  ...o,
});
const date = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "datetime", ...o });
const ref = (key: string, label: string, resource: string, o: Opts = {}): FieldDef => ({
  key,
  label,
  type: "ref",
  ref: resource,
  filter: true,
  ...o,
});
const json = (key: string, label: string, o: Opts = {}): FieldDef => ({ key, label, type: "json", ...o });

const created = () => date("createdAt", "Created");
const updated = () => date("updatedAt", "Updated");
const deleted = () => date("deletedAt", "Deleted");
const currency = (o: Opts = {}) => enm("currency", "Currency", CURRENCIES, { filter: false, raw: true, ...o });
const location = (editable = true) => [
  text("city", "City", { editable, nullable: true, max: 80 }),
  text("region", "Region", { editable, nullable: true, max: 80 }),
  text("country", "Country", { editable, nullable: true, max: 60 }),
];

