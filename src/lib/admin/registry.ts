/**
 * The admin data registry.
 *
 * Every table the console can browse is described here once: which columns it
 * shows, which fields staff may edit, how a row is deleted and who may do it.
 * The list page, the record page, the API and the CSV export are all driven
 * from these definitions, so adding a table to the console is one entry here.
 *
 * It is an allow-list, not a mirror of the schema. A field that is not listed
 * is never selected, never sent to the browser and never writable — which is
 * how password hashes, token hashes, client secrets, delivery OTP hashes and
 * the bodies of outgoing emails (which carry sign-in links) stay out of the
 * console without anyone having to remember them.
 *
 * Shared by server and client: no server-only imports.
 */

export type AdminPermission =
  | "admin:read"
  | "admin:users"
  | "admin:moderation"
  | "admin:finance"
  | "admin:settings"
  | "admin:destructive";

export type FieldType =
  | "id"
  | "ref"
  | "text"
  | "textarea"
  | "email"
  | "url"
  | "int"
  | "float"
  | "money"
  | "bps"
  | "boolean"
  | "enum"
  | "datetime"
  | "json";

export interface FieldDef {
  key: string;
  label: string;
  type: FieldType;
  options?: readonly string[];
  /** Resource key a `ref` field points at. */
  ref?: string;
  editable?: boolean;
  nullable?: boolean;
  min?: number;
  max?: number;
  /** For `money`: the sibling field holding the currency code. */
  currencyField?: string;
  hint?: string;
  /** Offered as a filter in the list toolbar. */
  filter?: boolean;
  /** Editing this field needs more than the resource's write permission. */
  permission?: AdminPermission;
  /** Option values are codes shown as-is (USD, EGP), not humanised. */
  raw?: boolean;
}

